#!/usr/bin/env python3
"""
reset_round.py - put the pipeline back to round 1, phase measure, with nothing measured.

WHY THIS EXISTS
  Starting clean was done by hand three times today, and twice it went wrong: a
  multi-file commit cannot delete a file, so a cleared BASELINE.md sat next to a
  RATCHET.json still holding twenty marks from an older verifier, and the first
  fresh run compared against a standard it could never meet. Doing a destructive
  thing by hand is how that happens.

  So the destructive thing is one command, it archives before it clears, and it
  prints exactly what it changed.

WHAT IT CLEARS
  BASELINE.md        every score emptied, all 208 rows kept
  RATCHET.json       emptied - the bar restarts from the first fresh measurement
  ATTEMPTS.json      removed - no class has been attempted in the new run
  DEFECT-CLASSES.md  regenerated empty
  ROUND.json         round 1, phase measure, no history
  RESULTS.jsonl      emptied - the recorded numbers belong to the old run

WHAT IT KEEPS
  Everything else. Each cleared file is copied into archive/reset-<timestamp>/
  first, so a reset is never a loss - it is a new attempt with the old one still
  readable. The corpus, the engine, the tools and the checks are untouched.

WHY EACH FILE HAS TO GO, NOT JUST SOME
  Clearing BASELINE but keeping RATCHET leaves a standard measured by a different
  instrument. Clearing both but keeping ATTEMPTS leaves a class marked PARKED for
  a run that no longer exists, and the fixer skips work it has never tried.
  Clearing ROUND but keeping DEFECT-CLASSES leaves a worklist for documents that
  have not been measured yet. The six files are one state; half a reset is a
  state that never existed.

USAGE
  python3 tools/p2w-bench/reset_round.py            # show what would change
  python3 tools/p2w-bench/reset_round.py --yes      # do it
"""
import json
import os
import shutil
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
FILES = {
    "BASELINE.md": None,          # rewritten, rows kept
    "RATCHET.json": "{}\n",
    "DEFECT-CLASSES.md": None,    # regenerated by classify.py
    "ROUND.json": json.dumps({"history": [], "phase": "measure", "round": 1,
                              "rounds_total": 3, "started": int(time.time())},
                             indent=2, sort_keys=True) + "\n",
}
REMOVE = ["ATTEMPTS.json", "RESULTS.jsonl"]


def count_state():
    s = {}
    base = os.path.join(HERE, "BASELINE.md")
    rows = scored = 0
    if os.path.exists(base):
        for line in open(base, encoding="utf-8"):
            if not line.startswith("| ") or line.startswith("|---"):
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if not cells or not cells[0] or cells[0].lower() == "document":
                continue
            rows += 1
            import re
            if re.match(r"\d+\s*/\s*\d+", cells[1] if len(cells) > 1 else ""):
                scored += 1
    s["baseline_rows"] = rows
    s["baseline_scored"] = scored
    p = os.path.join(HERE, "RATCHET.json")
    try:
        s["ratchet_marks"] = len(json.load(open(p, encoding="utf-8")))
    except Exception:
        s["ratchet_marks"] = 0
    p = os.path.join(HERE, "ATTEMPTS.json")
    try:
        s["attempts"] = len(json.load(open(p, encoding="utf-8")))
    except Exception:
        s["attempts"] = 0
    p = os.path.join(HERE, "RESULTS.jsonl")
    s["results_lines"] = sum(1 for _ in open(p, encoding="utf-8")) if os.path.exists(p) else 0
    p = os.path.join(HERE, "ROUND.json")
    try:
        d = json.load(open(p, encoding="utf-8"))
        s["round"] = d.get("round")
        s["phase"] = d.get("phase")
    except Exception:
        s["round"] = "?"
        s["phase"] = "?"
    return s


def main(argv):
    do = "--yes" in argv
    before = count_state()
    print("current state")
    for k, v in before.items():
        print("  %-16s %s" % (k, v))

    if not do:
        print("\nthis would:")
        print("  empty every BASELINE score, keeping all %d rows" % before["baseline_rows"])
        print("  empty RATCHET.json (%d marks)" % before["ratchet_marks"])
        print("  remove ATTEMPTS.json and RESULTS.jsonl")
        print("  regenerate DEFECT-CLASSES.md empty")
        print("  set ROUND.json to round 1, phase measure")
        print("  archive all of it first")
        print("\nnothing changed. run with --yes to do it.")
        return 0

    stamp = time.strftime("%Y%m%d-%H%M%S")
    arch = os.path.join(HERE, "archive", "reset-%s" % stamp)
    os.makedirs(arch, exist_ok=True)
    for name in list(FILES) + REMOVE:
        p = os.path.join(HERE, name)
        if os.path.exists(p):
            shutil.copy(p, os.path.join(arch, name))
    print("\narchived to archive/reset-%s/" % stamp)

    # BASELINE: empty the scores, keep every row
    base = os.path.join(HERE, "BASELINE.md")
    out, cleared = [], 0
    for line in open(base, encoding="utf-8"):
        if line.startswith("| ") and not line.startswith("|---"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if cells and cells[0] and cells[0].lower() != "document":
                # Seven cells since the universe stamp: a cleared row still has to
                # hold the column, or the next row written into it lands one cell short.
                out.append("| %s |  |  |  |  |  |  |" % cells[0])
                cleared += 1
                continue
        out.append(line.rstrip("\n"))
    open(base, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("BASELINE.md   : %d scores cleared, %d rows kept" % (cleared, cleared))

    for name, content in FILES.items():
        if content is None:
            continue
        open(os.path.join(HERE, name), "w", encoding="utf-8").write(content)
        print("%-13s : reset" % name)

    for name in REMOVE:
        p = os.path.join(HERE, name)
        if os.path.exists(p):
            os.remove(p)
            print("%-13s : removed" % name)

    # regenerate the class list from the now-empty baseline
    r = os.system("%s %s >/dev/null 2>&1" % (sys.executable,
                                             os.path.join(HERE, "classify.py")))
    print("DEFECT-CLASSES: regenerated (%s)" % ("ok" if r == 0 else "classify failed"))

    after = count_state()
    print("\nnow")
    for k, v in after.items():
        print("  %-16s %s" % (k, v))

    bad = [k for k in ("baseline_scored", "ratchet_marks", "attempts", "results_lines")
           if after.get(k)]
    if bad or after.get("phase") != "measure" or after.get("round") != 1:
        print("\nRESET DID NOT COMPLETE - still dirty: %s" % (bad or "round/phase"))
        return 1
    print("\nclean. round 1, phase measure, nothing measured.")
    print("commit BASELINE.md, RATCHET.json, DEFECT-CLASSES.md, ROUND.json and archive/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
