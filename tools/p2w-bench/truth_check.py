#!/usr/bin/env python3
"""truth_check.py - where the measurement's reference text cannot be trusted.

WHY. Every .docx score in this pipeline is a comparison against `glyph_truth`, which reads the PDF
with PyMuPDF. That reference is not the page; it is one reader's opinion of the page. On
041122-Account_Opening_Form it is demonstrably wrong:

    the page draws            "Please fill up in BLOCK letters only"
    PyMuPDF (the truth)       "Please Ĥll up in BLOCK letters only"     13 times
    poppler (pdftotext)       "Please �ll up in BLOCK letters only"
    our engine (the .docx)    "Please �ll up in BLOCK letters only"

`Ĥ` is U+0124, LATIN CAPITAL LETTER H WITH CIRCUMFLEX. It is not a character that document
contains. PyMuPDF invented it where the font gave no mapping; poppler and the engine both admit the
glyph cannot be decoded. So `t01_word_accuracy` compares `Ĥll` against `�ll`, finds no match, and
charges the document for a word neither side got right - and no engine change can win that
comparison, because the string being compared is not the string on the page.

This tool answers one question, per document: **do two independent readers agree on the text?**
Where they do not, the score for that document rests on a reference that is at least partly invented,
and a fix aimed at it is aimed at the wrong target.

    python3 tools/p2w-bench/truth_check.py --all
    python3 tools/p2w-bench/truth_check.py --docs a,b,c
    python3 tools/p2w-bench/truth_check.py --all --write     # write TRUTH-CHECK.md

Exit 1 when any document is contested, so a caller can gate on it.
"""
import argparse, csv, json, os, subprocess, sys, warnings

warnings.filterwarnings("ignore")

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
CORPUS = "/scratch/work/p2w/corpus"
RANK = os.path.join(ROOT, "benchmarks", "RANKING.csv")
OUT = os.path.join(HERE, "TRUTH-CHECK.md")

# A word-count difference under this is line-wrapping, not a disagreement about the text.
TOL_ABS = 3
TOL_REL = 0.02
# Below this the document is too small for a ratio to mean anything.
MIN_WORDS = 40


def pymupdf_text(pdf):
    import fitz
    with fitz.open(pdf) as d:
        return "".join(pg.get_text() for pg in d)


def poppler_text(pdf):
    r = subprocess.run(["pdftotext", pdf, "-"], capture_output=True, text=True, timeout=90)
    return r.stdout


def check(pdf):
    a = pymupdf_text(pdf)
    b = poppler_text(pdf)
    wa, wb = len(a.split()), len(b.split())
    if max(wa, wb) < MIN_WORDS:
        return {"pymupdf": wa, "poppler": wb, "verdict": "too small to judge"}
    ok = abs(wa - wb) <= max(TOL_ABS, TOL_REL * max(wa, wb))
    # U+FFFD on poppler's side with none on PyMuPDF's is the signature of an invented character.
    invented = b.count("\ufffd") - a.count("\ufffd")
    verdict = "agree" if ok else "CONTESTED"
    return {"pymupdf": wa, "poppler": wb, "fffd_poppler": b.count("\ufffd"),
            "fffd_pymupdf": a.count("\ufffd"), "invented_by_pymupdf": max(0, invented),
            "verdict": verdict}


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--docs", default="")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)

    if a.docs:
        docs = [x.strip() for x in a.docs.split(",") if x.strip()]
    elif a.all:
        docs = [r["document"] for r in csv.DictReader(open(RANK, encoding="utf-8"))]
    else:
        ap.print_help()
        return 2

    rows = []
    for d in docs:
        p = os.path.join(CORPUS, d + ".pdf")
        if not os.path.exists(p):
            continue
        try:
            r = check(p)
        except Exception as e:
            r = {"verdict": "error: %s" % type(e).__name__}
        r["document"] = d
        rows.append(r)
        if r["verdict"] != "agree":
            print("  %-44s %-16s pymupdf=%-5s poppler=%-5s fffd=%s"
                  % (d[:44], r["verdict"], r.get("pymupdf"), r.get("poppler"),
                     r.get("fffd_poppler")))

    contested = [r for r in rows if r["verdict"] not in ("agree", "too small to judge")]
    print("\n  %d checked | %d agree | %d CONTESTED" % (len(rows), len(rows) - len(contested),
                                                        len(contested)))

    if a.write:
        L = ["# Where the truth cannot be trusted", "",
             "Generated by `truth_check.py`. A CONTESTED row means PyMuPDF and poppler disagree on",
             "the document's text by more than 2 %%, so a score computed against `glyph_truth` rests",
             "on a reference that is at least partly one reader's invention.", "",
             "| document | verdict | PyMuPDF words | poppler words | U+FFFD (poppler) |",
             "|:--|:--|--:|--:|--:|"]
        for r in sorted(rows, key=lambda x: x["verdict"] == "agree"):
            L.append("| `%s` | %s | %s | %s | %s |"
                     % (r["document"], r["verdict"], r.get("pymupdf", "-"),
                        r.get("poppler", "-"), r.get("fffd_poppler", "-")))
        open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
        print("  wrote tools/p2w-bench/TRUTH-CHECK.md")

    return 1 if contested else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
