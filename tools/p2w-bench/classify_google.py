#!/usr/bin/env python3
"""Regenerate benchmarks/DEFECT-CLASSES-GOOGLE.md from the Google and LibreOffice measurements.

    python3 tools/p2w-bench/classify_google.py            # write the table
    python3 tools/p2w-bench/classify_google.py --check    # is it stale? exit 1 if it is
    python3 tools/p2w-bench/classify_google.py --print    # the table, without writing

WHY THIS EXISTS. The table said, in its own header, "Regenerated by the classifier every run". It was
not. Four tools read it - attempt.py, classpick.py, cronreport.py, round.py - and nothing wrote it; the
last version was produced by hand on 20 Nov. That is the same stale-table failure the .txt half had: its
class table claimed 64 failing documents while the ranking said 46, so a fixer reading it aimed at a
corpus that no longer existed.

It matters more here than anywhere else. classpick.py ranks THIS table by document count to decide what
each run works on, and round.py refuses to close a round while a row here says OPEN. A table that is not
regenerated is a rotation aimed at yesterday's problems and a round that can never close.

The counts come from benchmarks/gverify/ (Google) and benchmarks/gverify-lo/ (LibreOffice), the same two
directories gverify.py writes. `open` is how many documents fail the check in Google; `fixed` is how many
of those the .docx passes in LibreOffice - a check LibreOffice passes and Google fails is the gap this
whole table exists to show.
"""
import json, glob, os, sys
from datetime import datetime, timezone, timedelta

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "benchmarks", "DEFECT-CLASSES-GOOGLE.md")
G = os.path.join(ROOT, "benchmarks", "gverify")
L = os.path.join(ROOT, "benchmarks", "gverify-lo")
IST = timezone(timedelta(hours=5, minutes=30))


def _engine_now():
    """The engine the corpus is built from right now - THE SAME QUANTITY THE STORE IS STAMPED WITH.

    THE STAMP IS NOT A COMMIT. Every verdict in benchmarks/gverify/ is keyed on
    `sha256(name+bytes of the .docx engine sources)[:16]` (gvbatch.py:26-76, the same quantity as
    regress.py:engine_fingerprint("docx"), TxtWriter.java excluded - it cannot change a .docx byte). This function answered `git log -1 --format=%h -- engine/`, an
    8-char abbreviation, so the coverage paragraph below compared it with a 16-char source hash and
    printed "HEAD is 85b8735f and 0 of the 212 Google results were measured on it" over 212 rows that
    were all measured on this tree's engine (981ff1fa35e2cf67). Measured 25 Nov; report.py carried the
    identical defect in engine_now(), and it is fixed the same way there.
    """
    # THE SCOPE, NOT EVERY .java. 27 Nov: this hashed EVERY file in engine/, so on a tree whose
    # store was stamped `a05b20eb05fe0fc8` (the .docx sources, TxtWriter.java excluded) it printed
    # `HEAD is 72ff003db5871587 and 0 of the 206 Google results were measured on it` - a hash that
    # differed from the stamp by one file the .docx pipeline never reads. gverify._engine_now() and
    # report.engine_now() were corrected the same way the same day; this reader was missed. The
    # quantity is the one the store is stamped with: regress.engine_fingerprint("docx").
    try:
        import regress as _rg
        _fp = _rg.engine_fingerprint("docx")
        if _fp and _fp != "NO-ENGINE-DIR":
            return _fp
    except Exception:
        pass
    try:
        return (json.load(open("/scratch/work/p2w/.stamp", encoding="utf-8")).get("engine") or "")[:16]
    except Exception:
        pass
    import subprocess as _sp
    try:
        r = _sp.run(["git", "-C", ROOT, "log", "-1", "--format=%h", "--",
                     "app/src/main/java/com/kavopdf/app/engine/"],
                    capture_output=True, text=True, timeout=20)
        return (r.stdout or "").strip()
    except Exception:
        return ""


def load(d, engine=None):
    """Results from one directory, optionally only those measured on one engine.

    THE TABLE CLAIMED "same engine" AND COUNTED FOUR. On 23 Nov gverify/ held results stamped
    98be7c3c (the tree), 462353f, 462353f9, and 23 with no stamp - and this loader took all of them,
    so the capability table ranked a population whose rows were measured on code that no longer
    exists. gverify's own report refused to write that table for exactly this reason: "a matrix over
    them would print a Google/LibreOffice pair measured on two different engines and call it same
    engine".

    With `engine` set, only results stamped with it are returned. A document measured on an older
    engine is not counted as failing and not counted as passing - it is not counted, and the header
    says how many were left out.
    """
    out = {}
    for f in glob.glob(os.path.join(d, "*.json")):
        try:
            j = json.load(open(f, encoding="utf-8"))
        except Exception:
            continue
        if j.get("status") == "page_count_refused":
            continue
        if engine and (j.get("engine") or "") != engine:
            continue
        out[j.get("name") or os.path.basename(f)[:-5]] = j
    return out


PAGE_CLASS = "00_page_count"


def counts():
    _eng = _engine_now()
    # THE FULL POPULATION, WITH AN HONEST HEADER. Filtering to the current engine left
    # 2 documents and a table nobody could act on; keeping every result and claiming
    # "same engine" was a lie. The third option is the right one: count them all, and say
    # in the header exactly which engines they came from and whether that is the tree.
    g, l = load(G), load(L)
    paired = sorted(set(g) & set(l))
    gf, lf = {}, {}
    # A PAGE-COUNT MISMATCH IS THE WORST DEFECT THERE IS, AND IT WAS BEING THROWN AWAY.
    #
    # gverify.py writes status page_count_refused when Google reflows the document onto a different
    # number of pages, and its own comment says why: "A REFUSAL, NOT A RESULT." That is right as a
    # measurement - a pixel score against the wrong page count means nothing - but it meant those
    # documents were then invisible: not scored, so not failing, so in no class, so no run ever looked
    # at them. Measured 20 Nov: 21 of 213.
    #
    # The user's own words: "original pdf me kai me sirf 1 page hai jabki docs me 2 page hai" - extra
    # pages are a defect. So a reflowed document is counted as failing its own class, at the top of the
    # table, where the rotation will reach it.
    # load() drops refused documents on purpose - they have no score. Read them separately, or the
    # class that exists to make them visible is empty. That is what happened on the first attempt.
    g_refused = set()
    for _f in glob.glob(os.path.join(G, "*.json")):
        try:
            _j = json.load(open(_f, encoding="utf-8"))
        except Exception:
            continue
        if _j.get("status") == "page_count_refused":
            g_refused.add(_j.get("name") or os.path.basename(_f)[:-5])
    for n in g_refused:
        gf[PAGE_CLASS] = gf.get(PAGE_CLASS, 0) + 1
        lf[PAGE_CLASS] = lf.get(PAGE_CLASS, 0) + 1 if l.get(n, {}).get("status") == "page_count_refused" else lf.get(PAGE_CLASS, 0)
    for n in paired:
        for c in (g[n].get("failed") or []):
            gf[c] = gf.get(c, 0) + 1
        for c in (l[n].get("failed") or []):
            lf[c] = lf.get(c, 0) + 1
    clean_g = sum(1 for n in paired if not (g[n].get("failed") or []))
    clean_l = sum(1 for n in paired if not (l[n].get("failed") or []))
    rows = []
    for c in gf:
        rows.append((c, gf[c], lf.get(c, 0)))
    rows.sort(key=lambda r: (-(r[1] - r[2]), -r[1]))
    return rows, len(paired), clean_g, clean_l


def render():
    rows, n, cg, cl = counts()
    if not n:
        return None
    now = datetime.now(IST).strftime("%Y-%m-%d %H:%M")
    L_ = []
    L_.append("# Defect classes — GOOGLE's, not LibreOffice's")
    L_.append("")
    L_.append("Generated from `benchmarks/gverify/` and `benchmarks/gverify-lo/`: **%d documents with both**" % n)
    L_.append("renders. Regenerated by `classify_google.py`, which the classifier cron runs — this "
              "file is a build product and must never be edited by hand.")
    L_.append("")
    # "ALL 42" WAS NEVER TRUE. The verdicts are a mix: on 24 Nov, 126 documents carry total=42, 2 carry
    # 44 and 62 carry 47, because checks were added over time and old results were never re-measured. A
    # reader told "passes all 42" over a document only ever offered 42 of the 47 known checks is being
    # told a pass it did not earn. The same hard-coded 42 was already removed from cronreport.py for this
    # exact reason, and it survived here.
    _totals = {}
    try:
        for _f in os.listdir(G):
            if not _f.endswith(".json"):
                continue
            _d = json.load(open(os.path.join(G, _f), encoding="utf-8"))
            if _d.get("status") == "page_count_refused":
                continue
            _totals[_d.get("total")] = _totals.get(_d.get("total"), 0) + 1
    except Exception:
        pass
    _mix = ", ".join("%s: %d" % (k, v) for k, v in sorted(_totals.items(), key=lambda x: (x[0] is None, x[0] or 0)))
    L_.append("    LibreOffice  %3d of %d pass every check they were offered" % (cl, n))
    L_.append("    Google Docs  %3d of %d pass every check they were offered" % (cg, n))
    L_.append("")
    L_.append("    checks applied per document: %s" % (_mix or "unknown"))
    # THE ENGINE COVERAGE, COMPUTED. This table claimed "same engine" for weeks while its rows came
    # from several: on 23 Nov the directory held results stamped 98be7c3c, 462353f, 462353f9 and a
    # few with no stamp, and the engine on HEAD had moved on. A reader cannot act on a table that
    # does not say what it measured, so it says it now.
    import collections as _c
    _gall = load(G)
    _cov = _c.Counter((j.get("engine") or "unstamped") for j in _gall.values())
    _now = _engine_now()
    _on_now = sum(v for k, v in _cov.items()
                  if k and _now and (k == _now or _now.startswith(k) or k.startswith(_now)))
    L_.append("")
    if _on_now == len(_gall):
        L_.append("Every result above was measured on engine `%s`, the engine in the tree." % _now)
    else:
        L_.append("**This is a record of what the renderers did to these documents, not a statement about "
                  "the engine on HEAD.** HEAD is `%s` and %d of the %d Google results were measured on it;"
                  " the rest came from %s. Re-measure before treating any row as the current behaviour."
                  % (_now, _on_now, len(_gall),
                     ", ".join("`%s` (%d)" % (k, v) for k, v in _cov.most_common() if k != _now) or "nowhere"))
    L_.append("")
    L_.append("Every other class table comes from `RANKING.csv`, a soffice render — a renderer no user opens.")
    L_.append("**A check LibreOffice passes and Google fails appears in no other table.**")
    L_.append("")
    L_.append("`round.py --close-round` reads this file. A round cannot close while a row here says OPEN.")
    L_.append("")
    L_.append("Last regenerated: %s IST" % now)
    L_.append("")
    L_.append("## Classes, ranked by gap (Google fails − LibreOffice fails)")
    L_.append("")
    # THE STATUS CELL IS THE GATE. round.py open_classes() counts a class as open when a row carries a
    # cell that is exactly "OPEN" - and the first version of this table had no such column, so
    # --close-round counted ZERO Google classes and would have closed a round with 145 documents still
    # failing in the renderer the user actually opens. A gate that reads a cell nobody writes is a gate
    # that is silently off. benchmarks/DEFECT-CLASSES.md has carried OPEN from the start; this and the
    # .txt table did not.
    L_.append("| signature | problem | open | status | fixed-in-LO-only | libreoffice | google |")
    L_.append("|---|---|---:|---|---:|---:|---:|")
    for c, gc, lc in rows:
        # `fixed` is the gap: documents that fail this check in GOOGLE but pass it in LibreOffice. That
        # is the number this table exists for - work that looks done in the proxy and is not done for
        # the user. The first version of this generator wrote the LibreOffice count into both columns,
        # which said 19 "fixed" where the truth is 19 documents LibreOffice draws and Google does not.
        gap = max(0, gc - lc)
        status = "OPEN" if gc else "FIXED"
        L_.append("| `%s` | %s | %d | %s | %d | %d | %d |" % (c, c, gc, status, gap, lc, gc))
    L_.append("")
    return "\n".join(L_)


def main(argv):
    body = render()
    if body is None:
        print("refused: benchmarks/gverify and gverify-lo share no documents - nothing to classify", file=sys.stderr)
        return 3
    if "--print" in argv:
        print(body)
        return 0
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if "--check" in argv:
        # the timestamp line always differs; compare the table rows only
        def rows_of(t):
            return [x for x in t.split("\n") if x.startswith("| `")]
        same = rows_of(old) == rows_of(body)
        print("  %s - %d rows" % ("up to date" if same else "STALE, regenerate it", len(rows_of(body))))
        return 0 if same else 1
    open(OUT, "w", encoding="utf-8").write(body)
    print("  wrote %s - %d rows" % (os.path.relpath(OUT, ROOT), body.count("\n| `")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
