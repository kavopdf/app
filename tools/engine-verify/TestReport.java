import com.kavopdf.app.engine.PdfEngine;
import java.io.*;
import java.util.*;

public class TestReport {
  static File W = new File(System.getProperty("java.io.tmpdir"), "kavopdf-engine-test");
  public static void main(String[] a) throws Exception {
    W.mkdirs();
    List<String[]> facts = new ArrayList<>();
    facts.add(new String[]{"Application", "KavoPDF"});
    facts.add(new String[]{"Version", "2.1.0  (build 18)"});
    facts.add(new String[]{"Package", "com.kavopdf.app"});
    facts.add(new String[]{"Device", "samsung SM-E045F"});
    facts.add(new String[]{"Android", "14  (API 34)"});
    facts.add(new String[]{"Generated", "2026-10-24 21:18:32"});
    facts.add(new String[]{"Entries", "7"});

    List<PdfEngine.Column> cols = Arrays.asList(
      new PdfEngine.Column("TIME", 1.6f),
      new PdfEngine.Column("RESULT", 0.7f),
      new PdfEngine.Column("TASK", 1.4f),
      new PdfEngine.Column("OUTPUT", 2.3f));

    String[][] data = {
      {"2026-10-24 19:53:59","OK","ToolsActivity","merged_protected.pdf"},
      {"2026-10-24 20:02:49","OK","LogActivity","kavopdf-activity-log.pdf"},
      {"2026-10-24 20:43:30","FAIL","ToolsActivity","that password is wrong"},
      {"2026-10-24 20:50:23","OK","ToolsActivity","merged_signed.pdf"},
      {"2026-10-24 20:52:52","OK","BookmarksActivity","merged_signed_bookmarks.pdf"},
      {"2026-10-24 21:04:11","OK","RedactActivity","merged_redacted.pdf"},
      {"2026-10-24 21:18:32","OK","ImageOcrActivity","scan_searchable.pdf"},
    };
    File out = new File(W, "log_designed.pdf");
    PdfEngine.report(out, "KAVOPDF", "Activity log", "Activity on this device",
      facts, cols, Arrays.asList(data),
      "Generated by KavoPDF. Passwords are never recorded.", 0xFF3B5BDB);
    System.out.println("report pages: " + PdfEngine.pageCount(out));
  }
}
